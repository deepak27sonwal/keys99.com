/* ---------------- FAVORITES (localStorage, shared across the site) ---------------- */

function getFavorites(){
  try{
    const favorites = JSON.parse(localStorage.getItem("keys99_favorites") || "[]");
    return Array.isArray(favorites) ? favorites : [];
  }catch(_){
    return [];
  }
}

function setFavoriteButtonState(isActive){
  const btn = $("favoriteBtn");
  btn.classList.toggle("saved", isActive);
  btn.textContent = isActive ? "♥" : "♡";
}

function toggleFavorite(){
  if(!project) return;
  let favorites = getFavorites();
  const isActive = favorites.includes(project.id);
  favorites = isActive ? favorites.filter(id => id !== project.id) : [...favorites, project.id];
  try{ localStorage.setItem("keys99_favorites", JSON.stringify(favorites)); }catch(_){}
  setFavoriteButtonState(!isActive);
  showToast(!isActive ? "Added to favorites" : "Removed from favorites");
}


/* ---------------- BOTTOM NAV ---------------- */

function initBottomNav(){
  const bottomNav = $("bottomNav");
  if(!bottomNav) return;
  bottomNav.addEventListener("click", event => {
    const button = event.target.closest("button");
    if(!button) return;
    const target = button.dataset.target;
    if(target === "home") window.location.href = SITE_ROOT + "index.html";
    else if(target === "search") window.location.href = SITE_ROOT + "projects/search.html";
    else if(target === "reels") window.location.href = SITE_ROOT + "reels.html";
    else if(target === "profile") window.location.href = SITE_ROOT + "profile.html";
  });
}


/* ---------------- LOAD ---------------- */

async function loadProject(){

  if(embeddedRow){
    renderProject(normalize(embeddedRow));
  }

  if(!requestedSlug){
    if(!embeddedRow) showError("No project was requested.");
    return;
  }

  try{
    const { data, error } = await supabaseClient
      .from("residential_projects")
      .select(P.PROJECT_DETAIL_SELECT)
      .eq("slug", requestedSlug)
      .eq("moderation_status", "published")
      .is("deleted_at", null)
      .maybeSingle();

    if(error) throw error;

    if(data){
      renderProject(normalize(data));
    }else if(!embeddedRow){
      showError("This project is not available.");
    }
  }catch(error){
    console.error("Keys99 project error:", error);
    if(!embeddedRow) showError("Unable to load project details. Please try again.");
  }
}


