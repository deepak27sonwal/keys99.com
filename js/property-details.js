/* ==========================================================
   KEYS99 PROJECT PAGE

   Two ways in:
   - /projects/<slug>/  generated by build/generate.js. The page
     already contains the content and the project row
     (window.__KEYS99_PROJECT__), so it renders with no network
     request; the live fetch below only refreshes it.
   - /projects/property-details.html?slug=<slug>  the fallback
     (never indexed) for a project published since the last build.

   The live fetch never replaces a generated page with an error:
   if it fails, the built content stays. Showing "not found" to a
   crawler on a page that has content would read as a soft 404.

   Section markup comes from js/project-core.js, the same code
   the generator uses.
   ========================================================== */

