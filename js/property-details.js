function renderMedia(p){
  const uploaded = $("uploadedVideos");
  const social = $("socialVideosWrap");
  uploaded.innerHTML = "";
  social.innerHTML = "";

  p.videos.forEach(v => {
    if(/\.(mp4|webm|ogg|mov)(\?|#|$)/i.test(v.url) || /supabase\.co\/storage\//i.test(v.url)){
      const card = document.createElement("div");
      card.className = "video-card";
      card.innerHTML = `<video controls playsinline preload="metadata"><source src="${P.escapeHtml(v.url)}"></video>
        <div class="media-caption">${P.escapeHtml(v.title || (v.type === "virtual_tour" ? "Virtual Tour" : "Project Video"))}</div>`;
      uploaded.appendChild(card);
    }else{
      const type = /youtu/i.test(v.url) ? "youtube" : /facebook|fb\.watch/i.test(v.url) ? "facebook" : /instagram/i.test(v.url) ? "instagram" : "";
      addSocialPlayer(social, v, type);
    }
  });

  $("uploadedVideosWrap").classList.toggle("hidden", !uploaded.children.length);
  $("mediaSection").classList.toggle("hidden", !uploaded.children.length && !social.children.length);
}

function addSocialPlayer(container, video, type){
  const label = type === "youtube" ? "YouTube" : type === "facebook" ? "Facebook" : type === "instagram" ? "Instagram" : "Video";
  const card = document.createElement("div");
  card.className = `social-card ${type}`;
  card.innerHTML = `<div class="social-head"><span>▶</span>${P.escapeHtml(video.title || label + " Video")}</div>`;

  const embed = getSocialEmbed(video.url, type);
  if(embed){
    const iframe = document.createElement("iframe");
    iframe.src = embed;
    iframe.title = `${project.name} ${label} video`;
    iframe.loading = "lazy";
    iframe.allow = "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share";
    iframe.allowFullscreen = true;
    card.appendChild(iframe);
  }
  const footer = document.createElement("div");
  footer.className = "social-footer";
  footer.innerHTML = `<a href="${P.escapeHtml(video.url)}" target="_blank" rel="noopener noreferrer">Open ${P.escapeHtml(label)} ↗</a>`;
  card.appendChild(footer);
  container.appendChild(card);
}

function getSocialEmbed(url, type){
  try{
    const u = new URL(url);
    if(type === "youtube"){
      let id = "";
      if(u.hostname.includes("youtu.be")) id = u.pathname.split("/").filter(Boolean)[0] || "";
      else if(u.searchParams.get("v")) id = u.searchParams.get("v");
      else{
        const parts = u.pathname.split("/").filter(Boolean);
        const i = parts.findIndex(x => ["shorts","embed","live"].includes(x));
        if(i >= 0) id = parts[i + 1] || "";
      }
      return id ? `https://www.youtube.com/embed/${encodeURIComponent(id)}?rel=0` : null;
    }
    if(type === "facebook"){
      return `https://www.facebook.com/plugins/video.php?href=${encodeURIComponent(url)}&show_text=false&width=500`;
    }
    if(type === "instagram"){
      const parts = u.pathname.split("/").filter(Boolean);
      const i = parts.findIndex(x => ["p","reel","reels","tv"].includes(x));
      if(i < 0 || !parts[i + 1]) return null;
      return `https://www.instagram.com/${parts[i] === "reels" ? "reel" : parts[i]}/${encodeURIComponent(parts[i + 1])}/embed/`;
    }
  }catch(_){}
  return null;
}


